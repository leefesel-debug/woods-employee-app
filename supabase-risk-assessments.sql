create or replace function public.approve_risk_assessment(p_assessment_id uuid, p_review_note text default '')
returns integer language plpgsql security definer set search_path = public
as $$
declare
  current_assessment public.risk_assessments%rowtype;
  next_version integer;
  version_snapshot jsonb;
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;
  select * into current_assessment from public.risk_assessments where id = p_assessment_id and active for update;
  if not found then raise exception 'Assessment not found'; end if;
  next_version := current_assessment.version + 1;
  select jsonb_build_object(
    'assessment', to_jsonb(current_assessment),
    'items', coalesce(jsonb_agg(to_jsonb(i) order by i.sort_order) filter (where i.id is not null), '[]'::jsonb)
  ) into version_snapshot
  from public.risk_items i where i.assessment_id = p_assessment_id and i.active;
  insert into public.risk_review_history(assessment_id,version,review_note,snapshot,reviewed_by)
  values(p_assessment_id,next_version,coalesce(p_review_note,''),version_snapshot,auth.uid());
  update public.risk_assessments set version=next_version,approval_status='approved',approved_at=now(),approved_by=auth.uid(),updated_by=auth.uid()
  where id=p_assessment_id;
  return next_version;
end $$;
grant execute on function public.approve_risk_assessment(uuid,text) to authenticated;

