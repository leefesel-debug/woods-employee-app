create extension if not exists pgcrypto;

create table if not exists public.risk_assessments (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  title text not null,
  assessment_type text not null check (assessment_type in ('fire','health_safety','food_safety')),
  scope text not null default '',
  responsible_person text not null,
  issue_date date not null,
  review_date date not null,
  approval_status text not null default 'draft' check (approval_status in ('draft','approved')),
  version integer not null default 1 check (version > 0),
  approved_at timestamptz,
  approved_by uuid references auth.users(id),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id),
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id)
);

create table if not exists public.risk_items (
  id uuid primary key default gen_random_uuid(),
  assessment_id uuid not null references public.risk_assessments(id) on delete cascade,
  section_title text not null,
  hazard text not null,
  people_at_risk text not null default '',
  harm text not null default '',
  controls text not null,
  control_status text not null default 'yes' check (control_status in ('yes','no','na')),
  is_ccp boolean not null default false,
  critical_limit text not null default '',
  monitoring text not null default '',
  corrective_action text not null default '',
  likelihood smallint not null default 1 check (likelihood between 1 and 5),
  severity smallint not null default 1 check (severity between 1 and 5),
  action_required text not null default '',
  action_owner text not null default '',
  action_due date,
  action_status text not null default 'not_required' check (action_status in ('not_required','open','in_progress','complete')),
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id),
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id)
);

create table if not exists public.risk_review_history (
  id bigint generated by default as identity primary key,
  assessment_id uuid not null references public.risk_assessments(id) on delete cascade,
  version integer not null,
  review_note text not null default '',
  snapshot jsonb not null,
  reviewed_at timestamptz not null default now(),
  reviewed_by uuid not null references auth.users(id),
  unique (assessment_id, version)
);

create table if not exists public.risk_acknowledgements (
  id bigint generated by default as identity primary key,
  assessment_id uuid not null references public.risk_assessments(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  version integer not null,
  acknowledged_at timestamptz not null default now(),
  unique (assessment_id, user_id, version)
);

create table if not exists public.risk_audit (
  id bigint generated by default as identity primary key,
  table_name text not null,
  record_id uuid not null,
  action text not null,
  changed_at timestamptz not null default now(),
  changed_by uuid references auth.users(id),
  previous_data jsonb,
  new_data jsonb
);

create or replace function public.audit_risk_change()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    new.updated_at = now();
    insert into public.risk_audit(table_name,record_id,action,changed_by,new_data)
    values(tg_table_name,new.id,'created',auth.uid(),to_jsonb(new));
    return new;
  elsif tg_op = 'UPDATE' then
    new.updated_at = now();
    new.updated_by = coalesce(auth.uid(),new.updated_by);
    insert into public.risk_audit(table_name,record_id,action,changed_by,previous_data,new_data)
    values(tg_table_name,new.id,'updated',auth.uid(),to_jsonb(old),to_jsonb(new));
    return new;
  else
    insert into public.risk_audit(table_name,record_id,action,changed_by,previous_data)
    values(tg_table_name,old.id,'deleted',auth.uid(),to_jsonb(old));
    return old;
  end if;
end $$;

drop trigger if exists risk_assessments_audit_trigger on public.risk_assessments;
create trigger risk_assessments_audit_trigger before insert or update or delete on public.risk_assessments for each row execute function public.audit_risk_change();
drop trigger if exists risk_items_audit_trigger on public.risk_items;
create trigger risk_items_audit_trigger before insert or update or delete on public.risk_items for each row execute function public.audit_risk_change();

