create policy "Staff can read risk assessments" on public.risk_assessments for select to authenticated using (active = true or public.is_admin());
drop policy if exists "Admins can manage risk assessments" on public.risk_assessments;
create policy "Admins can manage risk assessments" on public.risk_assessments for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "Staff can read risk items" on public.risk_items;
create policy "Staff can read risk items" on public.risk_items for select to authenticated
using ((active and exists (select 1 from public.risk_assessments a where a.id = risk_items.assessment_id and a.active)) or public.is_admin());
drop policy if exists "Admins can manage risk items" on public.risk_items;
create policy "Admins can manage risk items" on public.risk_items for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "Staff can read review history" on public.risk_review_history;
create policy "Staff can read review history" on public.risk_review_history for select to authenticated
using (exists (select 1 from public.risk_assessments a where a.id = risk_review_history.assessment_id and (a.active or public.is_admin())));
drop policy if exists "Admins can add review history" on public.risk_review_history;
create policy "Admins can add review history" on public.risk_review_history for insert to authenticated with check (public.is_admin() and reviewed_by = auth.uid());

drop policy if exists "Users can read own acknowledgements" on public.risk_acknowledgements;
create policy "Users can read own acknowledgements" on public.risk_acknowledgements for select to authenticated using (user_id = auth.uid() or public.is_admin());
drop policy if exists "Users can acknowledge assessments" on public.risk_acknowledgements;
create policy "Users can acknowledge assessments" on public.risk_acknowledgements for insert to authenticated
with check (user_id = auth.uid() and exists (select 1 from public.risk_assessments a where a.id = risk_acknowledgements.assessment_id and a.active and a.version = risk_acknowledgements.version));

drop policy if exists "Admins can read risk audit" on public.risk_audit;
create policy "Admins can read risk audit" on public.risk_audit for select to authenticated using (public.is_admin());

create index if not exists risk_items_assessment_order_idx on public.risk_items (assessment_id, sort_order) where active = true;
